/**
 * EvaluationConsolidatedScoreSheet — Section 6.2
 * Multi-bidder consolidated evaluation score result sheet.
 * Includes AI→Manual→Adjudication→Appeal state machine.
 */
import { useState } from "react";
import { ProcurementDocumentTemplate, type ProcDocMeta } from "@/components/ui/ProcurementDocumentTemplate";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { CheckCircle2, XCircle, Bot, Edit3, Gavel, Scale, AlertTriangle } from "lucide-react";

// ── Evaluation state machine ───────────────────────────────────────────────
export type EvalStatus = "AI-Generated" | "Manually-Overridden" | "Adjudication" | "Appeal" | "Final";

const EVAL_STATUS_FLOW: Record<EvalStatus, { next?: EvalStatus; label: string; color: string }> = {
  "AI-Generated":       { next: "Manually-Overridden", label: "AI Generated", color: "bg-blue-100 text-blue-700" },
  "Manually-Overridden":{ next: "Adjudication",        label: "Manual Override", color: "bg-amber-100 text-amber-700" },
  "Adjudication":       { next: "Appeal",              label: "Adjudication", color: "bg-orange-100 text-orange-700" },
  "Appeal":             { next: "Final",               label: "Appeal", color: "bg-purple-100 text-purple-700" },
  "Final":              {                              label: "Final Decision", color: "bg-emerald-100 text-emerald-700" },
};

// ── Types ─────────────────────────────────────────────────────────────────────
export type BidderTechResult = {
  rank: number;
  bidderName: string;
  technicalScore: number; // raw %
  weightedTechnicalScore: number;
  technicalThreshold: number;
  passedTechnical: boolean;
};

export type BidderFinancialResult = {
  bidderName: string;
  tenderPrice: number;
  lowestPrice: number;
  financialWeight: number;
  financialScore: number;
  formula: string; // e.g. "(12.45/12.95)×20"
};

export type CombinedResult = {
  finalRank: number;
  bidderName: string;
  technicalWeighted: number;
  financialWeighted: number;
  totalCombined: number;
  recommendation: string;
};

export type EvalCommitteeMember = {
  role: string;
  fullName: string;
  position: string;
  dateTime?: string;
};

export type EvaluationConsolidatedProps = {
  meta: ProcDocMeta;
  sectionA: {
    procuringEntity: string;
    procuringDepartment: string;
    tenderNumber: string;
    tenderTitle: string;
    procurementMethod: string;
    financialYear: string;
    closingDate: string;
    evaluationDate: string;
    evaluationCommitteeRef: string;
    numberOfBiddersReceived: number;
    numberOfResponsiveBidders: number;
    currency: string;
    evaluationMethodology: string;
    technicalWeight: number; // e.g. 80
    financialWeight: number; // e.g. 20
  };
  technicalResults: BidderTechResult[];
  financialResults: BidderFinancialResult[];
  combinedResults: CombinedResult[];
  committee: EvalCommitteeMember[];
  initialEvalStatus?: EvalStatus;
};

function fmtCurrency(n: number, currency = "USD") {
  return `${currency} ${n.toLocaleString("en-US", { minimumFractionDigits: 2 })}`;
}

// ── Evaluation State Machine Banner ──────────────────────────────────────────
function EvalStatusMachine({ status, onOverride }: { status: EvalStatus; onOverride: () => void }) {
  const cfg = EVAL_STATUS_FLOW[status];
  return (
    <div className="mb-4 flex items-center gap-3 bg-slate-50 border border-gray-200 rounded p-3">
      {status === "AI-Generated" && <Bot className="h-5 w-5 text-blue-600 flex-shrink-0" />}
      {status === "Manually-Overridden" && <Edit3 className="h-5 w-5 text-amber-600 flex-shrink-0" />}
      {status === "Adjudication" && <Gavel className="h-5 w-5 text-orange-600 flex-shrink-0" />}
      {status === "Appeal" && <Scale className="h-5 w-5 text-purple-600 flex-shrink-0" />}
      {status === "Final" && <CheckCircle2 className="h-5 w-5 text-emerald-600 flex-shrink-0" />}
      <div className="flex-1">
        <p className="text-xs font-semibold text-gray-700">Evaluation Status: <Badge className={cfg.color}>{cfg.label}</Badge></p>
        <p className="text-[10px] text-gray-500 mt-0.5">
          {status === "AI-Generated" && "Results automatically generated by the AI Evaluation Engine. Evaluators may dispute and switch to manual mode."}
          {status === "Manually-Overridden" && "An evaluator has overridden the AI result. Routed to Adjudicator for independent review."}
          {status === "Adjudication" && "Under independent adjudication. Adjudicator is reviewing the manual override."}
          {status === "Appeal" && "Appeal stage — final ruling pending. The appeal decision is binding."}
          {status === "Final" && "Final decision recorded. Results are binding and cannot be further appealed."}
        </p>
      </div>
      {status === "AI-Generated" && (
        <Button size="sm" variant="outline" className="gap-1 text-xs text-amber-700 border-amber-300 hover:bg-amber-50" onClick={onOverride}>
          <Edit3 className="h-3 w-3" /> Dispute &amp; Override
        </Button>
      )}
    </div>
  );
}

export function EvaluationConsolidatedScoreSheet({
  meta,
  sectionA,
  technicalResults,
  financialResults,
  combinedResults,
  committee,
  initialEvalStatus = "AI-Generated",
}: EvaluationConsolidatedProps) {
  const [evalStatus, setEvalStatus] = useState<EvalStatus>(initialEvalStatus);
  const currency = sectionA.currency || meta.currency || "USD";

  const recommendedBidder = combinedResults.find(r => r.finalRank === 1);

  return (
    <ProcurementDocumentTemplate
      meta={meta}
      documentTitle="Tender Evaluation Consolidated Score Result Sheet"
      documentSubtitle="Final Evaluation Results — All Bidders"
      onPrint={() => window.print()}
    >
      {/* Evaluation status machine */}
      <EvalStatusMachine
        status={evalStatus}
        onOverride={() => setEvalStatus("Manually-Overridden")}
      />

      {/* Section A — Tender Details */}
      <section className="mb-6">
        <h2 className="text-xs font-bold uppercase tracking-widest text-[#1a6b3a] border-b border-[#1a6b3a] pb-1 mb-3">
          Section A — Tender Details
        </h2>
        <div className="grid grid-cols-2 md:grid-cols-3 gap-3 text-xs">
          {[
            ["Procuring Entity",           sectionA.procuringEntity],
            ["Procuring Department",       sectionA.procuringDepartment],
            ["Tender Number",              sectionA.tenderNumber],
            ["Tender Title",               sectionA.tenderTitle],
            ["Procurement Method",         sectionA.procurementMethod],
            ["Financial Year",             sectionA.financialYear],
            ["Closing Date",               sectionA.closingDate],
            ["Evaluation Date",            sectionA.evaluationDate],
            ["Evaluation Committee Ref",   sectionA.evaluationCommitteeRef],
            ["No. of Bidders Received",    sectionA.numberOfBiddersReceived],
            ["No. of Responsive Bidders",  sectionA.numberOfResponsiveBidders],
            ["Currency",                   currency],
            ["Evaluation Methodology",     sectionA.evaluationMethodology],
            [`Technical Weight`,           `${sectionA.technicalWeight}%`],
            [`Financial Weight`,           `${sectionA.financialWeight}%`],
          ].map(([label, value]) => (
            <div key={String(label)} className="border border-gray-200 rounded p-2">
              <p className="font-semibold uppercase tracking-wide text-gray-400 mb-0.5 text-[10px]">{label}</p>
              <p className="font-medium text-gray-900">{value}</p>
            </div>
          ))}
        </div>
      </section>

      {/* Section B — Technical Evaluation Results */}
      <section className="mb-6">
        <h2 className="text-xs font-bold uppercase tracking-widest text-[#1a6b3a] border-b border-[#1a6b3a] pb-1 mb-3">
          Section B — Technical Evaluation Results
        </h2>
        <div className="overflow-x-auto border border-gray-200 rounded">
          <table className="w-full text-xs">
            <thead>
              <tr className="bg-[#1a6b3a] text-white">
                {["Rank", "Bidder Name", "Technical Score (%)", `Weighted Tech. Score (×${sectionA.technicalWeight}%)`, `Threshold (${technicalResults[0]?.technicalThreshold ?? 70}%)`, "Passed"].map(h => (
                  <th key={h} className="px-3 py-2.5 text-left font-semibold uppercase tracking-wide whitespace-nowrap">{h}</th>
                ))}
              </tr>
            </thead>
            <tbody className="divide-y divide-gray-100">
              {technicalResults.map((r, i) => (
                <tr key={r.bidderName} className={i % 2 === 0 ? "bg-white" : "bg-gray-50"}>
                  <td className="px-3 py-2 font-bold text-gray-700">{r.rank}</td>
                  <td className="px-3 py-2 font-medium text-gray-900">{r.bidderName}</td>
                  <td className="px-3 py-2 font-mono text-gray-800">{r.technicalScore.toFixed(2)}%</td>
                  <td className="px-3 py-2 font-mono font-bold text-gray-900">{r.weightedTechnicalScore.toFixed(2)}</td>
                  <td className="px-3 py-2 font-mono text-gray-500">{r.technicalThreshold}%</td>
                  <td className="px-3 py-2">
                    {r.passedTechnical
                      ? <span className="flex items-center gap-1 text-emerald-700"><CheckCircle2 className="h-3.5 w-3.5" /> Pass</span>
                      : <span className="flex items-center gap-1 text-red-600"><XCircle className="h-3.5 w-3.5" /> Non-compliance</span>
                    }
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </section>

      {/* Section C — Financial Evaluation Results */}
      <section className="mb-6">
        <h2 className="text-xs font-bold uppercase tracking-widest text-[#1a6b3a] border-b border-[#1a6b3a] pb-1 mb-3">
          Section C — Financial Evaluation Results
        </h2>
        <div className="overflow-x-auto border border-gray-200 rounded">
          <table className="w-full text-xs">
            <thead>
              <tr className="bg-[#1a6b3a] text-white">
                {["Bidder", "Tender Price", "Formula Applied", "Financial Score"].map(h => (
                  <th key={h} className="px-3 py-2.5 text-left font-semibold uppercase tracking-wide whitespace-nowrap">{h}</th>
                ))}
              </tr>
            </thead>
            <tbody className="divide-y divide-gray-100">
              {financialResults.map((r, i) => (
                <tr key={r.bidderName} className={i % 2 === 0 ? "bg-white" : "bg-gray-50"}>
                  <td className="px-3 py-2 font-medium text-gray-900">{r.bidderName}</td>
                  <td className="px-3 py-2 font-mono text-gray-800">{fmtCurrency(r.tenderPrice, currency)}</td>
                  <td className="px-3 py-2 font-mono text-gray-600">{r.formula}</td>
                  <td className="px-3 py-2 font-mono font-bold text-gray-900">{r.financialScore.toFixed(2)}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </section>

      {/* Section D — Combined Score */}
      <section className="mb-6">
        <h2 className="text-xs font-bold uppercase tracking-widest text-[#1a6b3a] border-b border-[#1a6b3a] pb-1 mb-3">
          Section D — Combined Technical &amp; Financial Score
        </h2>
        <div className="overflow-x-auto border border-gray-200 rounded">
          <table className="w-full text-xs">
            <thead>
              <tr className="bg-[#1a6b3a] text-white">
                {["Final Rank", "Bidder", "Technical (Weighted)", "Financial (Weighted)", "Total Combined Score", "Recommendation"].map(h => (
                  <th key={h} className="px-3 py-2.5 text-left font-semibold uppercase tracking-wide whitespace-nowrap">{h}</th>
                ))}
              </tr>
            </thead>
            <tbody className="divide-y divide-gray-100">
              {combinedResults.map((r, i) => (
                <tr key={r.bidderName} className={`${i % 2 === 0 ? "bg-white" : "bg-gray-50"} ${r.finalRank === 1 ? "ring-1 ring-inset ring-emerald-400" : ""}`}>
                  <td className={`px-3 py-2 font-black text-lg ${r.finalRank === 1 ? "text-emerald-700" : "text-gray-500"}`}>#{r.finalRank}</td>
                  <td className="px-3 py-2 font-medium text-gray-900">{r.bidderName}</td>
                  <td className="px-3 py-2 font-mono text-gray-800">{r.technicalWeighted.toFixed(2)}</td>
                  <td className="px-3 py-2 font-mono text-gray-800">{r.financialWeighted.toFixed(2)}</td>
                  <td className="px-3 py-2 font-mono font-black text-gray-900 text-sm">{r.totalCombined.toFixed(2)}</td>
                  <td className="px-3 py-2">
                    <Badge className={r.finalRank === 1 ? "bg-emerald-600 text-white" : r.finalRank === 2 ? "bg-blue-100 text-blue-700" : "bg-gray-100 text-gray-600"}>
                      {r.recommendation}
                    </Badge>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </section>

      {/* Section E — Committee Recommendation */}
      <section className="mb-6">
        <h2 className="text-xs font-bold uppercase tracking-widest text-[#1a6b3a] border-b border-[#1a6b3a] pb-1 mb-3">
          Section E — Evaluation Committee Recommendation
        </h2>
        <div className="bg-emerald-50 border border-emerald-200 rounded p-4 text-sm text-gray-800 leading-relaxed">
          {recommendedBidder ? (
            <p>
              The Tender Evaluation Committee (TEC) recommends the award of{" "}
              <strong>{sectionA.tenderTitle}</strong> (Ref: {sectionA.tenderNumber}) to{" "}
              <strong>{recommendedBidder.bidderName}</strong>, who achieved the highest combined evaluation score of{" "}
              <strong>{recommendedBidder.totalCombined.toFixed(2)} points</strong> after applying the approved{" "}
              {sectionA.evaluationMethodology} methodology ({sectionA.technicalWeight}:{sectionA.financialWeight} Technical:Financial weighting).
              The recommended bidder demonstrated full technical compliance, financial competitiveness, and implementation
              capability consistent with the requirements of this tender.
            </p>
          ) : (
            <p>No clear recommendation available. Please review the evaluation results.</p>
          )}
        </div>
      </section>

      {/* Section F — Approvals */}
      <section className="mb-6">
        <h2 className="text-xs font-bold uppercase tracking-widest text-[#1a6b3a] border-b border-[#1a6b3a] pb-1 mb-3">
          Section F — Approvals
        </h2>
        <div className="overflow-x-auto border border-gray-200 rounded">
          <table className="w-full text-xs">
            <thead>
              <tr className="bg-[#1a6b3a] text-white">
                {["Role", "Full Name", "Position", "Signature", "Date &amp; Time"].map(h => (
                  <th key={h} className="px-4 py-2.5 text-left font-semibold uppercase tracking-wide" dangerouslySetInnerHTML={{ __html: h }} />
                ))}
              </tr>
            </thead>
            <tbody className="divide-y divide-gray-100">
              {committee.map((m, i) => (
                <tr key={i} className={i % 2 === 0 ? "bg-white" : "bg-gray-50"}>
                  <td className="px-4 py-3 font-semibold text-gray-700">{m.role}</td>
                  <td className="px-4 py-3 font-medium text-gray-900">{m.fullName}</td>
                  <td className="px-4 py-3 text-gray-700">{m.position}</td>
                  <td className="px-4 py-3">
                    <div className="border-b border-dashed border-gray-300 w-36 pb-3" />
                  </td>
                  <td className="px-4 py-3 text-gray-500">{m.dateTime ?? "—"}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </section>

      {/* Adjudication / Appeal conditional block */}
      {(evalStatus === "Adjudication" || evalStatus === "Appeal" || evalStatus === "Final") && (
        <section className="mb-6 border border-orange-200 rounded p-4 bg-orange-50">
          <div className="flex items-start gap-2">
            <AlertTriangle className="h-4 w-4 text-orange-600 flex-shrink-0 mt-0.5" />
            <div>
              <h3 className="text-xs font-bold uppercase tracking-wide text-orange-700 mb-2">
                {evalStatus === "Final" ? "Adjudication / Appeal — Final Ruling" : "Adjudication / Appeal in Progress"}
              </h3>
              <div className="grid grid-cols-2 gap-3 text-xs">
                <div className="border border-orange-200 rounded p-2 bg-white">
                  <p className="font-semibold text-gray-400 uppercase tracking-wide text-[10px] mb-0.5">Adjudicated By</p>
                  <div className="border-b border-dashed border-gray-300 w-full pb-4" />
                </div>
                <div className="border border-orange-200 rounded p-2 bg-white">
                  <p className="font-semibold text-gray-400 uppercase tracking-wide text-[10px] mb-0.5">Appeals Ruling By</p>
                  <div className="border-b border-dashed border-gray-300 w-full pb-4" />
                </div>
              </div>
            </div>
          </div>
        </section>
      )}

      {/* Annexure note */}
      <div className="border-t pt-4 text-xs text-gray-500 italic">
        Annexure A — Detailed Bidder Debrief Reports are attached separately per bidder (see Tender Evaluation Result Sheet — Specific Bidder).
      </div>

      <p className="text-[10px] text-gray-400 text-center mt-4">
        End of Report · {sectionA.tenderNumber} · {sectionA.evaluationDate}
      </p>
    </ProcurementDocumentTemplate>
  );
}
