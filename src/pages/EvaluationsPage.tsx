import { useState } from "react";
import { AppShell, PageHeader, Card, CardHeader, Badge, KpiCard , PageContextBar } from "@/components/AppShell";
import { useAuth } from "@/lib/auth-context";
import { pushSeniorAlert, pushNotification } from "@/lib/local-store";
import { toast } from "@/lib/toast";
import { Sparkles, Brain, FileSearch, ScanLine, CheckCircle2, AlertTriangle, Download, Send, ExternalLink, Trophy, ClipboardList } from "lucide-react";
import TechnicalEvaluationModule from "@/components/TechnicalEvaluationModule";
import InlineWorkbench from "@/components/InlineWorkbench";

const EVAL_SAMPLES = [
  { tender: "ZW-PRA-2026-00183 — ARV Medicines Framework", phase: "Technical Evaluation", method: "QCBS", bidders: 8, status: "Scoring" },
  { tender: "ZW-PRA-2026-00179 — Audit Services", phase: "Financial Evaluation", method: "QCBS", bidders: 9, status: "Moderation" },
  { tender: "ZW-PRA-2026-00180 — Pfumvudza Fertiliser", phase: "Combined Evaluation", method: "Least Cost", bidders: 14, status: "Award Recommendation" },
  { tender: "ZW-PRA-2026-00178 — School Textbooks", phase: "Administrative", method: "Open", bidders: 12, status: "Compliance Check" },
];

const BIDS = [
  { v: "Zimbabwe Pharma Holdings", s: [92, 88, 95, 80, 90], rec: "Strong" },
  { v: "Continental Med Africa", s: [88, 82, 90, 85, 87], rec: "Strong" },
  { v: "Sable Pharma", s: [78, 70, 75, 70, 80], rec: "Acceptable" },
  { v: "Granite Med Supplies", s: [60, 55, 65, 60, 62], rec: "Marginal" },
];

const W = [0.40, 0.20, 0.15, 0.10, 0.15];

export default function EvaluationsPage() {
  const [activePhase, setActivePhase] = useState(0);
  const [scores, setScores] = useState(BIDS.map(b => [...b.s]));
  const [submitted, setSubmitted] = useState(false);
  const [mainTab, setMainTab] = useState<"overview" | "technical">("overview");
  const { user } = useAuth();

  const handleOpen = (tender: string, phase: string) => {
    toast(`Evaluation Workbench — ${tender} | Phase: ${phase}. Use the Evaluator Workbench below to score bids.`, "info");
  };

  const handleSubmitScores = () => {
    setSubmitted(true);
    pushSeniorAlert(
      `Evaluation scores submitted: ZW-PRA-2026-00183 ARV Medicines — ${user?.name}`,
      "success",
      { from: user?.name, fromRole: user?.role ?? "evaluator", category: "action", ref: "ZW-PRA-2026-00183" }
    );
    pushNotification("Evaluation scores submitted for moderation", "success");
  };

  const downloadReport = (tender: string) => {
    const content = `EVALUATION REPORT\n\nTender: ${tender}\nEvaluator: ${user?.name ?? "System"}\nDate: ${new Date().toLocaleDateString()}\n\nScores:\n${BIDS.map((b, bi) => `${b.v}: ${scores[bi].reduce((a, v, i) => a + v * W[i], 0).toFixed(2)}/100`).join("\n")}\n\nGenerated by AI Powered Electronic Public Procurement and Oversight Intelligence System`;
    const blob = new Blob([content], { type: "application/octet-stream" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a"); a.href = url; a.download = "evaluation-report.txt"; a.click();
    URL.revokeObjectURL(url);
    pushNotification("Evaluation report downloaded", "success");
  };

  const phases = [
    { phase: "Phase 11", title: "Administrative", icon: ScanLine, desc: "Compliance matrix, mandatory requirements, eligibility, bid security, responsive determination." },
    { phase: "Phase 12", title: "Technical", icon: Brain, desc: "Supplies / Works / Services scoring with custom weights, pass marks, CV evaluation, OCR document intelligence." },
    { phase: "Phase 13", title: "Financial", icon: FileSearch, desc: "BOQ validation, arithmetic checks, cost realism, abnormally low bid detection, life-cycle costing." },
    { phase: "Phase 14", title: "Combined", icon: Sparkles, desc: "QCBS / QBS / LRB / LERB ranking engine with AI award recommendation and explainable scoring." },
  ];

  return (
    <AppShell>
      {/* Page Context Bar */}
      <PageContextBar
        ministry="Government of Zimbabwe"
        module="Procurement"
        process="Tender Evaluation"
        financialYear="FY2026"
        pageType="workbench"
      />
      <div className="p-4 sm:p-6 max-w-[1600px] mx-auto">
        <div className="mb-3 flex items-center gap-2 flex-wrap">
          <Badge tone="blue">Phases 11 – 14</Badge>
          <Badge tone="muted">Government of Zimbabwe</Badge>
        </div>
        <PageHeader
          title="AI Evaluation Engine"
          description="Administrative, Technical, Financial, and Combined evaluation workbench with dynamic weighted scoring, consensus, moderation, and explainable AI narratives."
        />

        <div className="grid grid-cols-2 md:grid-cols-4 gap-3 mb-6">
          <KpiCard label="Active Evaluations" value="42" delta="+3 new today" />
          <KpiCard label="Pending Moderation" value="8" delta="2 overdue" positive={false} />
          <KpiCard label="AI Recommendations" value="34" delta="Awaiting approval" />
          <KpiCard label="Completed This Month" value="127" delta="+18%" />
        </div>

        {/* ── Main module tabs ─────────────────────────────────────────── */}
        <div className="flex gap-1 mb-5 border-b border-border">
          {([
            { key: "overview"  as const, label: "Overview & Scoring",           icon: ScanLine    },
            { key: "technical" as const, label: "Technical Evaluation Module",   icon: ClipboardList, badge: "Full Spec" },
          ]).map(t => (
            <button key={t.key} onClick={() => setMainTab(t.key)}
              className={`flex items-center gap-2 px-4 py-2.5 text-sm font-medium border-b-2 -mb-px whitespace-nowrap transition-colors
                ${mainTab === t.key ? "border-primary text-primary" : "border-transparent text-foreground/65 hover:text-foreground"}`}>
              <t.icon className="h-4 w-4" />
              {t.label}
              {t.badge && <span className="text-[10px] bg-slate-100 text-[#0F172A] px-1.5 py-0.5 rounded-full font-semibold">{t.badge}</span>}
            </button>
          ))}
        </div>

        {mainTab === "technical" && (
          <div className="h-[calc(100vh-280px)] min-h-[600px] border border-border overflow-hidden rounded-xl">
            <TechnicalEvaluationModule
              tender="ZW-PRA-2026-00183 — ARV Medicines Framework"
              evaluator={user?.name ?? "D. Moyo"}
            />
          </div>
        )}

        {mainTab === "overview" && (<>
        <div className="grid grid-cols-1 lg:grid-cols-4 gap-3 mb-6">
          {phases.map((p, i) => (
            <div
              key={p.title}
              onClick={() => setActivePhase(i)}
            >
            <Card
              className={`p-4 cursor-pointer transition-all hover:border-primary/40 ${activePhase === i ? "border-primary bg-primary/5" : ""}`}
            >
              <div className="flex items-center gap-2 mb-2">
                <p.icon className="h-4 w-4 text-primary" />
                <Badge tone="blue">{p.phase}</Badge>
              </div>
              <div className="text-sm font-semibold text-foreground">{p.title} Evaluation</div>
              <div className="text-xs text-muted-foreground mt-1 leading-relaxed">{p.desc}</div>
            </Card>
            </div>
          ))}
        </div>

        {/* Active evaluations */}
        <Card className="mb-6">
          <CardHeader title="Active Evaluations" />
          <div className="divide-y divide-border">
            {EVAL_SAMPLES.map((s, i) => (
              <div key={i} className="px-4 sm:px-5 py-3 flex flex-col sm:flex-row sm:items-center sm:justify-between gap-2">
                <div className="min-w-0">
                  <div className="text-sm font-medium text-foreground">{s.tender}</div>
                  <div className="text-[11px] text-muted-foreground">{s.phase} · {s.method} · {s.bidders} bidders</div>
                </div>
                <div className="flex items-center gap-2 flex-shrink-0">
                  <Badge tone={s.status === "Award Recommendation" ? "green" : s.status === "Moderation" ? "amber" : "blue"}>{s.status}</Badge>
                  <button onClick={() => handleOpen(s.tender, s.phase)} className="h-7 px-2.5 rounded-md border border-border text-xs hover:bg-secondary transition-colors">Open</button>
                </div>
              </div>
            ))}
          </div>
        </Card>

        {/* Evaluator Workbench — Technical Evaluation (Supplies) */}
        <Card>
          <CardHeader
            title="Technical Evaluation Workbench (Supplies Evaluation)"
            subtitle="ZW-PRA-2026-00183 · ARV Medicines Framework · 8 Bidders"
            action={<Badge tone="blue"><Sparkles className="h-3 w-3 mr-1" />AI assisted</Badge>}
          />
          <div className="overflow-x-auto">
            <table className="w-full text-sm">
              <thead className="bg-secondary/50 text-xs text-muted-foreground">
                <tr>
                  {["#", "Bidder", "Specification (40%)", "Delivery (20%)", "Mfr Auth. (15%)", "Warranty (10%)", "Quality (15%)", "Weighted Score", "Result", "AI Rec.", "File"].map((h) => (
                    <th key={h} className="text-left font-medium px-3 py-2.5 whitespace-nowrap">{h}</th>
                  ))}
                </tr>
              </thead>
              <tbody className="divide-y divide-border">
                {BIDS.map((r, bi) => {
                  // Compute all weighted scores for ranking
                  const allScores = scores.map((s) => s.reduce((a, b, i) => a + b * W[i], 0));
                  const sorted = [...allScores].sort((a, b) => b - a);
                  const score = allScores[bi];
                  const rank = sorted.indexOf(score) + 1;

                  const resultLabel =
                    rank === 1 ? "1. Winner" :
                    rank === 2 ? "2. Runner-up" :
                    rank === 3 ? "3. Unsuccessful" :
                    `${rank}. Unsuccessful`;

                  const resultStyle =
                    rank === 1 ? "bg-slate-100 text-[#0F172A] border-slate-200" :
                    rank === 2 ? "bg-slate-100 text-[#0F172A] border-slate-200" :
                    "bg-gray-100 text-gray-500 border-gray-200";

                  return (
                    <tr key={r.v} className={`hover:bg-secondary/40 ${rank === 1 ? "bg-slate-50/30" : ""}`}>
                      {/* Number / Rank */}
                      <td className="px-3 py-3">
                        <div className={`h-6 w-6 rounded-full flex items-center justify-center text-[10px] font-bold border ${rank === 1 ? "bg-slate-400 text-white border-slate-200" : rank === 2 ? "bg-slate-100 text-[#0F172A] border-slate-200" : "bg-gray-100 text-gray-500 border-gray-200"}`}>
                          {rank === 1 ? <Trophy className="h-3 w-3" /> : rank}
                        </div>
                      </td>
                      {/* Bidder */}
                      <td className="px-3 py-3 font-medium text-foreground whitespace-nowrap">{r.v}</td>
                      {/* Score inputs */}
                      {scores[bi].map((sc, ci) => (
                        <td key={ci} className="px-2 py-3">
                          <input
                            type="number" min={0} max={100}
                            value={sc}
                            disabled={submitted}
                            onChange={e => {
                              const next = scores.map((row, ri) =>
                                ri === bi ? row.map((v, i) => i === ci ? Number(e.target.value) : v) : row
                              );
                              setScores(next);
                            }}
                            className={`w-14 h-7 text-center text-xs border rounded-lg focus:outline-none focus:ring-1 focus:ring-black/20 disabled:opacity-60 ${sc >= 85 ? "border-slate-200 bg-slate-50 text-[#0F172A]" : sc >= 70 ? "border-black/10 bg-white" : "border-red-200 bg-red-50 text-red-600"}`}
                          />
                        </td>
                      ))}
                      {/* Weighted Score */}
                      <td className="px-3 py-3 font-bold text-primary whitespace-nowrap">{score.toFixed(2)}</td>
                      {/* Result */}
                      <td className="px-3 py-3">
                        <span className={`text-[10px] font-semibold px-2 py-0.5 rounded-full border whitespace-nowrap ${resultStyle}`}>
                          {resultLabel}
                        </span>
                      </td>
                      {/* AI Rec */}
                      <td className="px-3 py-3">
                        <div className="flex items-center gap-1.5">
                          {r.rec === "Strong" ? <CheckCircle2 className="h-3.5 w-3.5 text-slate-600" /> : <AlertTriangle className="h-3.5 w-3.5 text-slate-600" />}
                          <Badge tone={r.rec === "Strong" ? "green" : r.rec === "Acceptable" ? "blue" : "amber"}>{r.rec}</Badge>
                        </div>
                      </td>
                      {/* View File */}
                      <td className="px-3 py-3">
                        <button
                          onClick={() => { pushNotification(`Opened evaluation form: ${r.v}`, "info"); }}
                          className="flex items-center gap-1 text-[10px] font-medium text-[#0F172A] hover:text-[#0F172A] hover:underline transition-colors whitespace-nowrap"
                        >
                          <ExternalLink className="h-3 w-3" /> View file
                        </button>
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
          {!submitted ? (
            <div className="px-5 py-3 border-t border-border flex items-center justify-between gap-3 flex-wrap">
              <div className="text-xs text-black/40">Review scores then submit for moderation. CPO will be notified.</div>
              <div className="flex gap-2">
                <button onClick={() => downloadReport("ZW-PRA-2026-00183")}
                  className="h-8 px-3 rounded-lg border border-border text-xs hover:bg-secondary transition-colors flex items-center gap-1.5">
                  <Download className="h-3.5 w-3.5" /> Download Draft
                </button>
                <button onClick={handleSubmitScores}
                  className="h-8 px-4 rounded-lg bg-[#0F172A] text-white text-xs font-semibold hover:bg-[#0F172A] transition-colors flex items-center gap-1.5">
                  <Send className="h-3.5 w-3.5" /> Submit Scores
                </button>
              </div>
            </div>
          ) : (
            <div className="px-5 py-3 bg-slate-50 border-t border-border flex items-center justify-between gap-3">
              <div className="flex items-center gap-2">
                <CheckCircle2 className="h-4 w-4 text-[#0F172A]" />
                <span className="text-sm text-[#0F172A] font-medium">Scores submitted · Awaiting moderation · CPO notified</span>
              </div>
              <button onClick={() => downloadReport("ZW-PRA-2026-00183")}
                className="h-8 px-3 rounded-lg border border-slate-200 text-xs text-[#0F172A] hover:bg-slate-100 transition-colors flex items-center gap-1.5">
                <Download className="h-3.5 w-3.5" /> Download Report
              </button>
            </div>
          )}
        </Card>
        </>)}
      </div>
      <InlineWorkbench context="Evaluations" />
    </AppShell>
  );
}
